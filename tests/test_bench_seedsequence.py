def test_corpus_draws_never_import_random() -> None:
    def imported(source: str) -> set[str]:
        names: set[str] = set()
        for node in ast.walk(ast.parse(source)):
            if isinstance(node, ast.Import):
                names.update(alias.name.partition(".")[0] for alias in node.names)
            elif isinstance(node, ast.ImportFrom) and node.module:
                names.add(node.module.partition(".")[0])
        return names

    assert "random" in imported("import random\n")
    assert "random" in imported("from random import Random\n")
    for module in (seeds, corpus_module):
        assert "random" not in imported(Path(str(module.__file__)).read_text(encoding="utf-8"))


@pytest.mark.parametrize(("seed", "grid", "digest"), NUMPY_CORPORA)
def test_corpus_matches_the_numpy_reference(seed: int, grid: Grid, digest: str) -> None:
    payload = corpus_module.build(grid, seed).payload()
    canonical = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    assert hashlib.sha256(canonical).hexdigest() == digest


def test_a_draw_skips_the_words_that_would_bias_it() -> None:
    outcomes = 2**31 + 1
    corpus = corpus_module.build(
        Grid(writers=2, tasks=8, files=2, conflict=0.0, jitter_ms=outcomes - 1), 13
    )
    thinks = [task.think_ms for writer in range(2) for task in corpus.tasks[writer]]
    assert thinks == NUMPY_THINKS_SEED_13
    # Known-bad control: each think node's first word reduced without rejecting any word.
    first = [
        SeedSequence(13, (writer, task, THINK)).generate_state(1)[0]
        for writer in range(2)
        for task in range(8)
    ]
    assert any(word >= 2**32 - 2**32 % outcomes for word in first)
    assert [word % outcomes for word in first] != thinks


def test_draws_refuse_ranges_one_word_cannot_cover() -> None:
    draws = TaskDraws(1, 0, 0)
    with pytest.raises(ValueError, match="between 1 and 2"):
        draws.choice([])
    with pytest.raises(ValueError, match="between 1 and 2"):
        draws.think_ms(2**32)
